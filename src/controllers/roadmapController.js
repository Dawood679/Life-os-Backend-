const Roadmap = require("../models/Roadmap");
const Todo = require("../models/Todo");
const lifeScoreService = require("../services/lifeScoreService");
const { ai, roadmapConfig } = require("../config/gemini");
const { callAIWithFallback } = require("../utils/aiWithFallback");

const buildPrompt = (goal) => `
  Generate a 90-Day (3-Month) Career Transformation Blueprint for: "${goal}".
  Provide exactly 3 phases with 2 to 3 sharp, practical milestones per phase:
  - Phase 1: Month 1 (Weeks 1-4) — Core Foundations & Diagnostic Skill Gaps
  - Phase 2: Month 2 (Weeks 5-8) — Proof-of-Work & Portfolio Capstones
  - Phase 3: Month 3 (Weeks 9-12) — Market Velocity, Targeted Mock Interviews & Salary Pitch
`;

const generateRoadmap = async (req, res) => {
  try {
    const { goal } = req.body;

    if (!goal) {
      return res.status(400).json({
        success: false,
        message: "Please provide a goal",
      });
    }

    // AI Call
    const prompt = buildPrompt(goal);
    const response = await callAIWithFallback(ai, roadmapConfig, prompt);

    console.log(
      `Roadmap generated by: ${response.provider} on attempt: ${response.attempt}`
    );

    const parsedRoadmap = response.parsed || JSON.parse(response.text);

    const rawPhases = Array.isArray(parsedRoadmap.phases)
      ? parsedRoadmap.phases
      : Array.isArray(parsedRoadmap.roadmap)
      ? parsedRoadmap.roadmap
      : [];

    // Sanitize phases and milestones safely
    const sanitizedPhases = rawPhases.map((phase, pIdx) => {
      const rawMilestones = Array.isArray(phase.milestones)
        ? phase.milestones
        : Array.isArray(phase.tasks)
        ? phase.tasks
        : Array.isArray(phase.steps)
        ? phase.steps
        : [];

      return {
        phaseNumber: Number(phase.phaseNumber || phase.phase) || pIdx + 1,
        phaseTitle: String(phase.phaseTitle || phase.title || `Phase ${pIdx + 1}`),
        phaseFocus: String(phase.phaseFocus || `Month ${pIdx + 1}`),
        milestones: rawMilestones.map((m) => ({
          title: String(m.title || m.name || "Milestone"),
          description: String(m.description || m.details || ""),
          estimatedWeeks: parseInt(m.estimatedWeeks || m.weeks, 10) || 1,
          category: String(m.category || "general"),
          actionBridge: {
            studyTopic: String(m.actionBridge?.studyTopic || m.title || ""),
            interviewTopic: String(m.actionBridge?.interviewTopic || m.title || ""),
            quizTopic: String(m.actionBridge?.quizTopic || m.title || ""),
            capstoneTitle: String(m.actionBridge?.capstoneTitle || "")
          },
          resources: Array.isArray(m.resources) ? m.resources.map(String) : [],
          isCompleted: false
        }))
      };
    });

    const roadmapTitle =
      parsedRoadmap.roadmapTitle ||
      parsedRoadmap.title ||
      parsedRoadmap.roadmap_title ||
      `${goal} 90-Day Transformation Blueprint`;

    const roadmap = await Roadmap.create({
      user: req.user._id,
      goal,
      title: roadmapTitle,
      duration: parsedRoadmap.duration || "90 Days (3 Months)",
      phases: sanitizedPhases,
      rawResponse: response.text,
    });

    res.status(201).json({
      success: true,
      message: "90-Day Transformation Roadmap generated successfully",
      roadmap,
    });
  } catch (error) {
    if (error.message && error.message.includes("All 5 attempts failed")) {
      return res.status(429).json({
        success: false,
        message: "Service temporarily unavailable. Please try again later.",
      });
    }
    console.error("Generate roadmap error:", error);
    res.status(500).json({
      success: false,
      message: "Server error generating roadmap",
    });
  }
};

const getRoadmaps = async (req, res) => {
  try {
    let page = parseInt(req.query.page, 10);
    let limit = parseInt(req.query.limit, 10);

    page = !isNaN(page) && page > 0 ? page : 1;
    limit = !isNaN(limit) && limit > 0 ? limit : 10;

    const skip = (page - 1) * limit;

    const [totalRoadmaps, roadmaps] = await Promise.all([
      Roadmap.countDocuments({ user: req.user._id }),
      Roadmap.find({ user: req.user._id })
        .sort({ createdAt: -1 })
        .skip(skip)
        .limit(limit),
    ]);

    const totalPages = Math.ceil(totalRoadmaps / limit) || 1;

    res.json({
      success: true,
      roadmaps,
      pagination: {
        totalRoadmaps,
        totalPages,
        currentPage: page,
        limit,
        hasNextPage: page < totalPages,
        hasPrevPage: page > 1,
      },
    });
  } catch (error) {
    console.error("Get roadmaps error:", error);
    res.status(500).json({
      success: false,
      message: "Server error fetching roadmaps",
    });
  }
};

const deleteRoadmap = async (req, res) => {
  try {
    const { id } = req.params;

    const roadmap = await Roadmap.findOneAndDelete({
      _id: id,
      user: req.user._id,
    });

    if (!roadmap) {
      return res.status(404).json({
        success: false,
        message: "Roadmap not found or unauthorized",
      });
    }

    res.json({
      success: true,
      message: "Roadmap deleted successfully",
    });
  } catch (error) {
    console.error("Delete roadmap error:", error);
    res.status(500).json({
      success: false,
      message: "Server error deleting roadmap",
    });
  }
};

/**
 * PATCH /api/roadmap/:id/phases/:phaseNumber/milestones/:milestoneId/toggle
 * Toggles completion of a specific roadmap milestone and records Life Score progress
 */
const toggleMilestone = async (req, res) => {
  try {
    const { id, phaseNumber, milestoneId } = req.params;

    const roadmap = await Roadmap.findOne({ _id: id, user: req.user._id });
    if (!roadmap) {
      return res.status(404).json({ success: false, message: "Roadmap not found." });
    }

    const phase = roadmap.phases.find((p) => String(p.phaseNumber) === String(phaseNumber));
    if (!phase) {
      return res.status(404).json({ success: false, message: "Phase not found." });
    }

    const milestone = phase.milestones.id(milestoneId);
    if (!milestone) {
      return res.status(404).json({ success: false, message: "Milestone not found." });
    }

    milestone.isCompleted = !milestone.isCompleted;
    milestone.completedAt = milestone.isCompleted ? new Date() : null;

    await roadmap.save();

    // Trigger Life Score recalculation for completed milestone
    let updatedScore = null;
    if (milestone.isCompleted) {
      try {
        updatedScore = await lifeScoreService.calculateDailyScore(req.user._id, new Date());
      } catch (scoreErr) {
        console.warn("LifeScore update warning on milestone toggle:", scoreErr);
      }
    }

    res.json({
      success: true,
      message: milestone.isCompleted ? "Milestone completed! +Life Score points earned 🚀" : "Milestone unmarked.",
      milestone,
      updatedScore,
    });
  } catch (error) {
    console.error("Toggle milestone error:", error);
    res.status(500).json({ success: false, message: "Server error updating milestone status." });
  }
};

/**
 * POST /api/roadmap/:id/phases/:phaseNumber/milestones/:milestoneId/bridge-todo
 * 1-Click Action Bridge: Adds the milestone directly as a scheduled Todo item in user's active agenda
 */
const bridgeMilestoneToTodo = async (req, res) => {
  try {
    const { id, phaseNumber, milestoneId } = req.params;
    const { targetDate, priority } = req.body;

    const roadmap = await Roadmap.findOne({ _id: id, user: req.user._id });
    if (!roadmap) {
      return res.status(404).json({ success: false, message: "Roadmap not found." });
    }

    const phase = roadmap.phases.find((p) => String(p.phaseNumber) === String(phaseNumber));
    if (!phase) {
      return res.status(404).json({ success: false, message: "Phase not found." });
    }

    const milestone = phase.milestones.id(milestoneId);
    if (!milestone) {
      return res.status(404).json({ success: false, message: "Milestone not found." });
    }

    const taskTitle = `[Roadmap] ${milestone.title}`;

    // Check if task already exists on user's active agenda
    const existingTodo = await Todo.findOne({
      user: req.user._id,
      title: taskTitle,
      isCompleted: false,
    });

    milestone.isBridgedToTodo = true;
    await roadmap.save();

    if (existingTodo) {
      return res.status(200).json({
        success: true,
        alreadyExists: true,
        message: "This milestone is already active on your Agenda!",
        todo: existingTodo,
        milestone,
      });
    }

    const todo = await Todo.create({
      user: req.user._id,
      title: taskTitle,
      priority: priority || "high",
      dueDate: targetDate ? new Date(targetDate) : new Date(),
    });

    res.status(201).json({
      success: true,
      alreadyExists: false,
      message: "Milestone scheduled directly to your Agenda / Todos! 📅",
      todo,
      milestone,
    });
  } catch (error) {
    console.error("Bridge milestone to todo error:", error);
    res.status(500).json({ success: false, message: "Server error scheduling milestone to todo." });
  }
};

module.exports = {
  generateRoadmap,
  getRoadmaps,
  deleteRoadmap,
  toggleMilestone,
  bridgeMilestoneToTodo,
};